const { Client, LocalAuth } = require('whatsapp-web.js');
const axios = require('axios');
const path = require('path');

console.log('======================================================');
console.log('🚀 Initializing Jamia Hamdard SMS WhatsApp AI Bot...');
console.log('======================================================');

const client = new Client({
    authStrategy: new LocalAuth({
        dataPath: path.join(__dirname, '.wwebjs_auth')
    }),
    puppeteer: {
        headless: false, // Opens visible Chrome window showing live WhatsApp Web with QR!
        executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',
        args: [
            '--no-sandbox',
            '--disable-setuid-sandbox'
        ]
    }
});

client.on('qr', () => {
    console.log('\n======================================================');
    console.log('⚡ A CHROME WINDOW HAS OPENED ON YOUR DESKTOP!');
    console.log('👉 Point your phone camera at the QR code on that Chrome window.');
    console.log('======================================================\n');
});

client.on('authenticated', () => {
    console.log('🔐 Session authenticated successfully!');
});

client.on('auth_failure', (msg) => {
    console.error('❌ Authentication failed:', msg);
});

client.on('ready', () => {
    console.log('\n======================================================');
    console.log('🎓 JAMIA SMS AI BOT IS ONLINE & READY!');
    console.log(`📱 Connected as WhatsApp user: ${client.info?.wid?.user || 'Active User'}`);
    console.log('🤖 AI Model: Google Gemini 2.5 Flash');
    console.log('📡 Connected Backend: http://127.0.0.1:8000/ai/chat');
    console.log('------------------------------------------------------');
    console.log('💡 How to test:');
    console.log('   In ANY WhatsApp chat (including "Message yourself"):');
    console.log('   Type: !ai Who is debarred from exams?');
    console.log('======================================================\n');
});

client.on('message_create', async (msg) => {
    const text = (msg.body || '').trim();

    // Trigger on !ai, !jamia, /ai, or !ask
    const prefixMatch = text.match(/^(!ai|!jamia|\/ai|!ask)\s+(.+)/i);

    if (prefixMatch) {
        const userQuery = prefixMatch[2].trim();
        console.log(`\n📩 [${new Date().toLocaleTimeString()}] Query: "${userQuery}"`);

        try {
            try { await msg.react('⏳'); } catch (e) {}

            const res = await axios.post('http://127.0.0.1:8000/ai/chat', {
                message: userQuery,
                role: 'admin'
            }, { timeout: 35000 });

            const reply = res.data.reply || 'No response generated by Jamia SMS AI.';
            
            await msg.reply(reply);
            try { await msg.react('✅'); } catch (e) {}
            console.log(`📤 [${new Date().toLocaleTimeString()}] Replied successfully.`);
        } catch (err) {
            console.error('❌ Error calling AI backend:', err.message);
            await msg.reply(`⚠️ Jamia SMS Backend Error: ${err.message}\nMake sure FastAPI is running on port 8000.`);
        }
    } else if (text.toLowerCase() === '!help') {
        await msg.reply(
            `🎓 *Jamia Hamdard SMS Academic Assistant*\n\n` +
            `Ask me anything using the *!ai* prefix:\n` +
            `• *!ai Who is debarred from exams?*\n` +
            `• *!ai What is my attendance? I am Atif Farooqui*\n` +
            `• *!ai Can Diya Patel download admit card?*\n` +
            `• *!ai How many classes does Diya need to reach 75%?*\n\n` +
            `_Powered by Google Gemini 2.5 Flash & Departmental SQLite DB_`
        );
    }
});

client.initialize();
